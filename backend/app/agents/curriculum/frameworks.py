def seed_frameworks(session) -> int:
    """Insert framework rows that don't yet exist. Returns number inserted."""
    import json as _json
    from .db import AccreditationFramework

    inserted = 0
    for fw in FRAMEWORKS:
        exists = session.query(AccreditationFramework).filter_by(name=fw["name"]).first()
        if exists:
            continue
        session.add(AccreditationFramework(
            name=fw["name"],
            organization=fw["organization"],
            description=fw["description"],
            country=fw["country"],
            industry=fw["industry"],
            competencies=_json.dumps(fw["competencies"]),
            url=fw["url"],
            last_updated=fw["last_updated"],
        ))
        inserted += 1
    session.commit()
    return inserted
